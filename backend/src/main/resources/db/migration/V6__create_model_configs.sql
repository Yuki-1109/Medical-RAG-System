CREATE TABLE model_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    config_type VARCHAR(16) NOT NULL CHECK (config_type IN ('CHAT','EMBEDDING')),
    protocol VARCHAR(32) NOT NULL CHECK (protocol = 'OPENAI_COMPATIBLE'),
    base_url VARCHAR(2048) NOT NULL,
    model_id VARCHAR(200) NOT NULL,
    encrypted_api_key TEXT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    test_status VARCHAR(16) NOT NULL DEFAULT 'UNTESTED' CHECK (test_status IN ('UNTESTED','SUCCESS','FAILED')),
    test_code VARCHAR(64),
    tested_at TIMESTAMPTZ,
    embedding_dimension INTEGER CHECK (embedding_dimension > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_id, config_type)
);
